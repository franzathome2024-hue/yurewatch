/**
 * Domain model.
 *
 * Everything the UI renders comes from these types. Wire formats (p2pquake /
 * JMA XML relays, demo scripts) are converted into these by adapters, so a
 * provider can be replaced without touching UI code.
 *
 * Times are epoch milliseconds (UTC) or `null` when the upstream did not
 * provide a usable value. Never substitute "now" for a missing upstream time —
 * the UI must be able to say "時刻不明".
 */

/** JMA seismic intensity, encoded as the integer scale used by JMA XML (scale × 10). */
export type JmaScale = -1 | 0 | 10 | 20 | 30 | 40 | 45 | 50 | 55 | 60 | 70 | 99;

/** Where a datum came from, and how much authority it carries. */
export type Authority =
  /** Issued by JMA, relayed unmodified by P2P地震情報. */
  | 'jma-via-p2pquake'
  /** Generated by this app's demo engine. Never official. */
  | 'simulation';

export interface SourceRef {
  authority: Authority;
  /** Human readable provider name for the UI. */
  provider: string;
  /** True only when the message originates from JMA. */
  official: boolean;
  /** True when a third-party relay sits between JMA and this app. */
  relayed: boolean;
  url?: string;
}

export interface Epicenter {
  /** JMA epicentre name, e.g. 三陸沖. */
  name: string | null;
  latitude: number;
  longitude: number;
  /** Depth in km. `0` is JMA's "ごく浅い". `-1` means unknown. */
  depthKm: number;
  /** `-1` means unknown / not announced. */
  magnitude: number;
  /** JMA marks hypocentres as 仮定震源要素 while the solution is poor. */
  provisional: boolean;
}

export interface ObservationPoint {
  /** JMA 府県 name, e.g. 熊本県. */
  pref: string;
  /** 観測点名 / 市区町村. */
  name: string;
  scale: JmaScale;
}

/** JMA 地震情報 announcement kind (how complete the message is). */
export type JmaQuakeType =
  | 'ScalePrompt'
  | 'Destination'
  | 'ScaleAndDestination'
  | 'DetailScale'
  | 'Foreign'
  | 'Other'
  | 'unknown';

export type TsunamiGrade =
  | 'None'
  | 'Unknown'
  | 'Checking'
  | 'NonEffective'
  | 'Watch'
  | 'Warning'
  | 'MajorWarning';

export interface EarthquakeEvent {
  /** Stable id for the UI/selection; derived from origin time + hypocentre. */
  id: string;
  /** Telegram ids that contributed to this event (for de-duplication/debug). */
  sourceIds: string[];
  originTime: number | null;
  issuedAt: number | null;
  receivedAt: number;
  infoType: JmaQuakeType;
  correction: string;
  epicenter: Epicenter | null;
  /** Max observed intensity across reported points; `-1` when not reported. */
  maxIntensity: JmaScale;
  points: ObservationPoint[];
  tsunami: TsunamiGrade;
  /** True when this event is a simulation. Must be surfaced in the UI. */
  simulated: boolean;
  /** How many telegrams have revised this event (1 = first report). */
  revision: number;
  /** True while the report is an early/preliminary announcement. */
  preliminary: boolean;
  source: SourceRef;
}

/** EEW presentation states. Mirrors the wording of JMA 緊急地震速報. */
export type EewState =
  /** No alert in force. */
  | 'idle'
  /** 緊急地震速報（予報）— prediction only, not a warning. */
  | 'forecast'
  /** 緊急地震速報（警報）— warning issued. */
  | 'warning'
  /** A warning whose content changed since the previous telegram. */
  | 'updated'
  /** 取消 — cancelled by the issuer. */
  | 'cancelled'
  /** Feed is unavailable; nothing can be said about the current alert state. */
  | 'unavailable';

export interface EewArea {
  /** 府県予報区, e.g. 北海道道東. */
  pref: string;
  /** 細分区域, e.g. 根室地方北部. */
  name: string;
  scaleFrom: JmaScale;
  scaleTo: JmaScale;
  /** JMA 警報コード: 10 = 主要動未到達, 11 = 到達済み, 19 = PLUM法 (到達予想なし). */
  kindCode: string;
  /** 主要動到達予測時刻 (epoch ms) when the source supplied one. */
  arrivalTime: number | null;
}

export interface EewAlert {
  eventId: string;
  serial: number;
  state: EewState;
  issuedAt: number | null;
  receivedAt: number;
  originTime: number | null;
  epicenter: Epicenter | null;
  areas: EewArea[];
  /** Highest predicted intensity across areas (`scaleTo`); `-1` if unknown. */
  maxScaleTo: JmaScale;
  /** True when the source flagged this as a test transmission (訓練/試験). */
  isTest: boolean;
  simulated: boolean;
  /** Increments on every accepted revision; used for animation/audio gating. */
  revision: number;
  source: SourceRef;
}

export interface TsunamiArea {
  grade: TsunamiGrade;
  name: string;
  immediate: boolean;
  arrivalTime: string | null;
  heightLabel: string | null;
  heightValue: number | null;
}

export interface TsunamiInfo {
  id: string;
  issuedAt: number | null;
  receivedAt: number;
  cancelled: boolean;
  areas: TsunamiArea[];
  source: SourceRef;
}

/** Health of the data pipeline, surfaced verbatim to the user. */
export type ConnectionState =
  | 'idle'
  | 'connecting'
  | 'live'
  | 'degraded'
  | 'stale'
  | 'offline'
  | 'demo';

/**
 * How old a datum is, relative to now.
 * `no-data` and `unknown` are deliberately distinct: the former means we have
 * nothing, the latter means we have something with no trustworthy timestamp.
 */
export type Freshness = 'fresh' | 'aging' | 'stale' | 'no-data' | 'unknown';

export interface FeedHealth {
  state: ConnectionState;
  lastSuccessAt: number | null;
  lastAttemptAt: number | null;
  lastError: string | null;
  consecutiveFailures: number;
}
